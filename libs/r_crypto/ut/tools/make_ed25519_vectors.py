#!/usr/bin/env python3
"""Writes ut/include/ed25519_vectors.h from RFC 8032 and Wycheproof's Ed25519 vectors.

    python3 make_ed25519_vectors.py rfc8032.txt ed25519_test.json > ../include/ed25519_vectors.h

rfc8032.txt is https://www.rfc-editor.org/rfc/rfc8032.txt, and ed25519_test.json is
testvectors_v1/ed25519_test.json from https://github.com/C2SP/wycheproof. Pass the
Wycheproof commit with --wycheproof-commit so the header says where it came from.
"""
import argparse
import json
import re
import sys

HEX = re.compile(r'^[0-9a-f]+$')


def rfc8032_vectors(text):
    # Section 7.1 only: Ed25519. 7.2 onwards are Ed25519ctx, Ed25519ph and Ed448. The headings are
    # also in the table of contents, so the last of each is the section's.
    section = text[text.rindex('7.1.  Test Vectors for Ed25519'):text.rindex('7.2.  Test Vectors for Ed25519ctx')]
    vectors = []
    for block in section.split('-----TEST ')[1:]:
        name = block.split('\n', 1)[0].strip()
        fields, current = {}, None
        for line in block.split('\n')[1:]:
            line = line.strip()
            if line.startswith('SECRET KEY'):
                current = 'seed'
            elif line.startswith('PUBLIC KEY'):
                current = 'public_key'
            elif line.startswith('MESSAGE'):
                current = 'msg'
            elif line.startswith('SIGNATURE'):
                current = 'signature'
            elif line.startswith('ALGORITHM'):
                current = None
            elif current and HEX.match(line):
                fields[current] = fields.get(current, '') + line
        fields.setdefault('msg', '')
        vectors.append((name, fields))
    return vectors


def c_string(s):
    # MSVC refuses string literals over about 16 KB, so long ones are split.
    return '\n        '.join('"%s"' % s[i:i + 120] for i in range(0, max(len(s), 1), 120)) if s else '""'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rfc8032')
    ap.add_argument('wycheproof')
    ap.add_argument('--wycheproof-commit', required=True)
    a = ap.parse_args()

    rfc = rfc8032_vectors(open(a.rfc8032).read())
    wp = json.load(open(a.wycheproof))
    results = {'valid': 'R_VALID', 'invalid': 'R_INVALID', 'acceptable': 'R_ACCEPTABLE'}

    out = []
    out.append('// Generated by tools/make_ed25519_vectors.py. Do not edit.')
    out.append('//   RFC 8032 section 7.1 (https://www.rfc-editor.org/rfc/rfc8032.txt)')
    out.append('//   Wycheproof testvectors_v1/ed25519_test.json, commit %s' % a.wycheproof_commit)
    out.append('//   (https://github.com/C2SP/wycheproof, Apache-2.0)')
    out.append('')
    out.append('#ifndef ed25519_vectors_h')
    out.append('#define ed25519_vectors_h')
    out.append('')
    out.append('struct rfc8032_vector { const char* name; const char* seed; const char* public_key; const char* msg; const char* signature; };')
    out.append('')
    out.append('static const rfc8032_vector RFC8032_ED25519[] = {')
    for name, f in rfc:
        out.append('    { "TEST %s",' % name)
        for k in ('seed', 'public_key', 'msg', 'signature'):
            out.append('        %s,' % c_string(f[k]))
        out.append('    },')
    out.append('};')
    out.append('')
    out.append('// Valid must verify, invalid must not. Acceptable (small- or mixed-order public')
    out.append("// keys) may go either way under RFC 8032's cofactored equation.")
    out.append('enum wycheproof_result { R_VALID, R_INVALID, R_ACCEPTABLE };')
    out.append('struct wycheproof_vector { int tc_id; const char* flag; const char* public_key; const char* msg; const char* signature; wycheproof_result result; };')
    out.append('')
    out.append('static const wycheproof_vector WYCHEPROOF_ED25519[] = {')
    for g in wp['testGroups']:
        pk = g['publicKey']['pk']
        for t in g['tests']:
            out.append('    { %d, "%s", "%s",\n        %s,\n        "%s", %s },' % (
                t['tcId'], ','.join(t['flags']), pk, c_string(t['msg']), t['sig'], results[t['result']]))
    out.append('};')
    out.append('')
    out.append('#endif')
    print('\n'.join(out))
    print('RFC 8032: %d vectors, Wycheproof: %d' % (len(rfc), sum(len(g['tests']) for g in wp['testGroups'])), file=sys.stderr)


if __name__ == '__main__':
    main()
