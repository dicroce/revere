#!/usr/bin/env python3
"""Writes ut/include/x25519_hkdf_aead_vectors.h from RFC 7748 and Wycheproof.

    python3 make_x25519_hkdf_aead_vectors.py rfc7748.txt wycheproof_dir --wycheproof-commit SHA \\
        > ../include/x25519_hkdf_aead_vectors.h

rfc7748.txt is https://www.rfc-editor.org/rfc/rfc7748.txt. wycheproof_dir holds
x25519_test.json, hkdf_sha512_test.json and chacha20_poly1305_test.json from
testvectors_v1 of https://github.com/C2SP/wycheproof at that commit.
"""
import argparse
import json
import os
import re


def rfc7748_alice_bob(text):
    # Section 6.1's Curve25519 test vector: two key pairs and their shared secret.
    s = text[text.rindex('6.1.  Curve25519'):text.rindex('6.2.  Curve448')]
    names = ["Alice's private key", "Alice's public key", "Bob's private key", "Bob's public key", 'Their shared secret']
    lines = s.split('\n')
    out = []
    for name in names:
        i = next(i for i, l in enumerate(lines) if l.strip().startswith(name))
        out.append(lines[i + 1].strip())
    return out


def c_string(h):
    return '\n        '.join('"%s"' % h[i:i + 120] for i in range(0, len(h), 120)) if h else '""'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rfc7748')
    ap.add_argument('wycheproof_dir')
    ap.add_argument('--wycheproof-commit', required=True)
    a = ap.parse_args()
    load = lambda f: json.load(open(os.path.join(a.wycheproof_dir, f)))
    results = {'valid': 'WP_VALID', 'invalid': 'WP_INVALID', 'acceptable': 'WP_ACCEPTABLE'}

    out = ['// Generated by tools/make_x25519_hkdf_aead_vectors.py. Do not edit.',
           '//   RFC 7748 section 6.1 (https://www.rfc-editor.org/rfc/rfc7748.txt)',
           '//   Wycheproof testvectors_v1 x25519_test.json, hkdf_sha512_test.json and',
           '//   chacha20_poly1305_test.json, commit %s' % a.wycheproof_commit,
           '//   (https://github.com/C2SP/wycheproof, Apache-2.0)',
           '', '#ifndef x25519_hkdf_aead_vectors_h', '#define x25519_hkdf_aead_vectors_h', '']

    ap_, apub, bp, bpub, k = rfc7748_alice_bob(open(a.rfc7748).read())
    out.append('// RFC 7748 6.1: Alice\'s and Bob\'s key pairs and their shared secret.')
    for name, v in (('ALICE_PRIVATE', ap_), ('ALICE_PUBLIC', apub), ('BOB_PRIVATE', bp), ('BOB_PUBLIC', bpub), ('ALICE_BOB_SHARED', k)):
        out.append('static const char* RFC7748_%s = "%s";' % (name, v))
    out.append('')

    out.append('// Named apart from ed25519_vectors.h, which a test can include as well.')
    out.append('enum wp_result { WP_VALID, WP_INVALID, WP_ACCEPTABLE };')
    out.append('')

    x = load('x25519_test.json')
    out.append('struct x25519_vector { int tc_id; const char* flags; const char* public_key; const char* private_key; const char* shared; wp_result result; };')
    out.append('static const x25519_vector WYCHEPROOF_X25519[] = {')
    for g in x['testGroups']:
        for t in g['tests']:
            out.append('    { %d, "%s", "%s", "%s", "%s", %s },' % (t['tcId'], ','.join(t['flags']), t['public'], t['private'], t['shared'], results[t['result']]))
    out.append('};')
    out.append('')

    h = load('hkdf_sha512_test.json')
    out.append('struct hkdf_vector { int tc_id; const char* ikm; const char* salt; const char* info; size_t size; const char* okm; wp_result result; };')
    out.append('static const hkdf_vector WYCHEPROOF_HKDF_SHA512[] = {')
    for g in h['testGroups']:
        for t in g['tests']:
            out.append('    { %d, %s,\n        %s,\n        %s,\n        %d,\n        %s, %s },' % (
                t['tcId'], c_string(t['ikm']), c_string(t['salt']), c_string(t['info']), t['size'], c_string(t['okm']), results[t['result']]))
    out.append('};')
    out.append('')

    c = load('chacha20_poly1305_test.json')
    out.append('struct aead_vector { int tc_id; const char* flags; const char* key; const char* nonce; const char* aad; const char* msg; const char* ct; const char* tag; wp_result result; };')
    out.append('static const aead_vector WYCHEPROOF_CHACHA20_POLY1305[] = {')
    for g in c['testGroups']:
        for t in g['tests']:
            out.append('    { %d, "%s", "%s", "%s",\n        %s,\n        %s,\n        %s,\n        "%s", %s },' % (
                t['tcId'], ','.join(t['flags']), t['key'], t['iv'], c_string(t['aad']), c_string(t['msg']), c_string(t['ct']), t['tag'], results[t['result']]))
    out.append('};')
    out += ['', '#endif']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
